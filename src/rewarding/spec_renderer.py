def render_reward_code_from_spec(reward_spec: Dict[str, Any]) -> str:
    validated_spec = validate_reward_spec(reward_spec)
    spec_literal = pformat(validated_spec, sort_dicts=True, width=88)
    return _MODULE_TEMPLATE.replace("__REWARD_SPEC_LITERAL__", spec_literal)


